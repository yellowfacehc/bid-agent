REGION_CONFIG = {
    "九龙坡区": JIULONGPO_DATA,
    "大渡口区": DADUKOU_DATA,
}

# 匹配优先级（权重从高到低）
MATCH_PRIORITY = [
    ("towns", 100),        # 行政街道/镇，最权威
    ("hospitals", 90),      # 医院全称
    ("schools", 80),         # 学校全称
    ("landmarks", 70),       # 商圈/地标/园区
    ("communities", 60),     # 社区/居委会
    ("roads", 50),           # 道路名称
    ("district_names", 40),  # 区名关键词（标题中直接包含区名，作为补充依据）
]


def analyze_region(text: str, extra_text: str = "") -> Optional[str]:
    """
    分析文本，判断归属的重庆区县。

    不依赖"九龙坡""大渡口"等区名关键词，
    而是通过道路、学校、医院、商圈等地理特征匹配。

    Args:
        text: 主要分析文本（如项目标题、采购人名称）
        extra_text: 补充文本（如地址、项目详情等）

    Returns:
        匹配到的区县名称（如"九龙坡区"），未匹配返回 None
    """
    if not text and not extra_text:
        return None

    full_text = f"{text} {extra_text}"
    if not full_text.strip():
        return None

    region_scores: Dict[str, int] = {}
    match_details: Dict[str, List[Tuple[str, str]]] = {}

    for region_name, region_data in REGION_CONFIG.items():
        total_score = 0
        details = []

        for category, weight in MATCH_PRIORITY:
            keywords = region_data.get(category, [])
            for kw in keywords:
                if kw and kw in full_text:
                    total_score += weight
                    details.append((category, kw))
                    # 同一类别只计一次最高分，避免重复累加
                    break

        if total_score > 0:
            region_scores[region_name] = total_score
            match_details[region_name] = details

    if not region_scores:
        return None

    # 返回得分最高的区域
    best_region = max(region_scores, key=region_scores.get)
    return best_region


def analyze_region_with_detail(text: str, extra_text: str = "") -> Dict:
    """
    分析文本并返回详细的匹配信息。

    Returns:
        {
            "region": "九龙坡区" / None,
            "score": 80,
            "matches": [("schools", "重庆市红光中学"), ...],
            "all_scores": {"九龙坡区": 80, "大渡口区": 0}
        }
    """
    if not text and not extra_text:
        return {"region": None, "score": 0, "matches": [], "all_scores": {}}

    full_text = f"{text} {extra_text}"
    region_scores: Dict[str, int] = {}
    match_details: Dict[str, List[Tuple[str, str]]] = {}

    for region_name, region_data in REGION_CONFIG.items():
        total_score = 0
        details = []

        for category, weight in MATCH_PRIORITY:
            keywords = region_data.get(category, [])
            for kw in keywords:
                if kw and kw in full_text:
                    total_score += weight
                    details.append((category, kw))
                    break

        region_scores[region_name] = total_score
        if details:
            match_details[region_name] = details

    best_region = max(region_scores, key=region_scores.get) if region_scores else None
    best_score = region_scores.get(best_region, 0) if best_region else 0

    return {
        "region": best_region if best_score > 0 else None,
        "score": best_score,
        "matches": match_details.get(best_region, []) if best_region else [],
        "all_scores": region_scores,
    }


def filter_by_regions(
    items: list,
    target_regions: List[str],
    title_field: str = "title",
    buyer_field: str = "buyer",
    region_field: str = "region",
    summary_field: str = "summary",
) -> list:
    """
    按目标区县过滤采购意向列表。

    过滤逻辑：
      1. 如果 item.region 已明确包含目标区县，直接保留
      2. 否则通过地理信息分析标题+采购人+摘要，判断归属
      3. 归属到目标区县的保留，否则过滤掉

    Args:
        items: BidItem 列表（或字典列表）
        target_regions: 目标区县列表，如 ["九龙坡区", "大渡口区"]
        title_field: 标题字段名
        buyer_field: 采购人字段名
        region_field: 地区字段名
        summary_field: 摘要字段名

    Returns:
        过滤后的列表
    """
    if not target_regions:
        return items

    filtered = []
    for item in items:
        # 支持对象和字典两种格式
        if hasattr(item, "title"):
            title = getattr(item, title_field, "") or ""
            buyer = getattr(item, buyer_field, "") or ""
            region = getattr(item, region_field, "") or ""
            summary = getattr(item, summary_field, "") or ""
        else:
            title = item.get(title_field, "") or ""
            buyer = item.get(buyer_field, "") or ""
            region = item.get(region_field, "") or ""
            summary = item.get(summary_field, "") or ""

        # 第一步：检查region字段是否已明确包含目标区县
        region_match = False
        for target in target_regions:
            if target in region:
                region_match = True
                break

        if region_match:
            filtered.append(item)
            continue

        # 第二步：通过地理信息分析判断归属
        # 组合标题+采购人+摘要进行分析
        analyze_text = f"{title} {buyer} {summary}"
        detected = analyze_region(analyze_text)

        if detected and detected in target_regions:
            # 更新region字段（如果原来是空的或"重庆市"）
            if hasattr(item, "region"):
                if not item.region or item.region == "重庆市":
                    item.region = detected
            else:
                if not item.get("region") or item.get("region") == "重庆市":
                    item["region"] = detected
            filtered.append(item)

    return filtered


